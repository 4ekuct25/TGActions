/**
 * Комнаты: что показывать и в каком порядке.
 *
 * Список ведётся руками, и по-другому нельзя: в объектной модели сценариев у
 * Room есть только getName() и getAccessories() — ни признака видимости, ни
 * порядка хаб сценарию не отдаёт (см. ScenarioTemplate/spruthub.js). В веб-
 * интерфейсе поля visible и order есть, но они доступны только UI.
 *
 * Один список задаёт сразу и порядок, и видимость: комната, которой здесь нет,
 * в бота не попадает вовсе — ни в меню, ни в /status. Так не нужно держать два
 * списка, которые неминуемо разъедутся.
 *
 * Значения ниже сняты с хаба «Усадьба» 2026-08-28: восемь видимых комнат в
 * порядке хаба. Скрытыми там были Терраса, Крыльцо, Спальня Александра,
 * Спальня Арина, Новая комната, Теплица — из них непустая только «Новая
 * комната» (камеры и водопроводный кран).
 *
 * Добавили комнату в хабе — допишите её сюда, иначе бот её не увидит.
 *
 * Зависимостей нет.
 */
function TGActionsRooms() {
    var order = [
        'Гостиная',
        'Улица',
        'Кабинет',
        'Бойлерная',
        'Детские комнаты',
        'Ванная 1 этаж',
        'Коридор',
        'Кухня'
    ];

    var rank = {};
    for (var i = 0; i < order.length; i++) {
        rank[order[i]] = i;
    }

    function isVisible(name) {
        return rank.hasOwnProperty(name);
    }

    /** Позиция комнаты; для неизвестной — в конец (в бот она всё равно не попадёт). */
    function rankOf(name) {
        return rank.hasOwnProperty(name) ? rank[name] : order.length;
    }

    /** Сортировка списка имён комнат в порядке хаба. */
    function sortNames(names) {
        return names.slice().sort(function (a, b) {
            return rankOf(a) - rankOf(b);
        });
    }

    return {
        order: order,
        isVisible: isVisible,
        rankOf: rankOf,
        sortNames: sortNames
    };
}
